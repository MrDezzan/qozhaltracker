-- Автоматические кадры животных отменяются.
-- Применять ПОСЛЕ 0017_animal_enrollment.sql.
--
-- Раньше система складывала снимок каждого прохода животного мимо камеры
-- в очередь «ждут имени», а человек должен был опознавать их на глаз.
-- Отказались по двум причинам.
--
-- Очередь не кончалась. Каждый визит добавлял в неё кадр, разбирать их
-- было некому, и она превращалась в свалку, которую перестают открывать.
--
-- Хуже другое: эталоны из этой очереди — догадки. Человек опознавал
-- животное по мутному кадру со спины, и ошибка закреплялась навсегда:
-- дальше система сравнивала новые кадры с неверным образцом. Теперь
-- эталоны берутся только из фото, загруженных осознанно (0017).
--
-- Строки о встречах остаются: они отвечают на вопрос «когда это
-- животное видели в последний раз». Но только для УЗНАННЫХ животных.

-- ---------------------------------------------------------------------------
-- 1. Больше не собираем эталоны из случайных кадров
-- ---------------------------------------------------------------------------
-- Триггер превращал каждый названный кадр в эталон. Именно он и делал
-- догадку образцом.

-- Имя ровно как в 0008. `drop trigger if exists` с опечаткой прошёл бы
-- без единого слова, а триггер остался бы работать — и продолжал бы
-- превращать догадки в эталоны.
drop trigger if exists sightings_promote_embedding on sightings;

-- Уже накопленные эталоны из кадров помечаем как ненадёжные, но не
-- удаляем: на ферме, где эталонных фото ещё нет, они остаются
-- единственным, что позволяет хоть что-то узнавать.
--
-- Убрать их совсем можно будет после того, как животные заведены
-- заново с фотографиями:
--   delete from animal_embeddings where source = 'sighting';

-- ---------------------------------------------------------------------------
-- 2. Кадра больше нет
-- ---------------------------------------------------------------------------
-- Колонка была обязательной с тех времён, когда снимок действительно
-- сохранялся. Оставляем её (история ссылается), но снимаем обязательность.

alter table sightings alter column crop_path drop not null;

comment on column sightings.crop_path is
  'Историческое поле. Кадры больше не сохраняются: у новых встреч пусто.';

-- ---------------------------------------------------------------------------
-- 3. Безымянные встречи больше не заводятся
-- ---------------------------------------------------------------------------
-- Проверка на будущее: если что-то снова попробует записать встречу без
-- животного, это будет ошибка, а не тихо растущая очередь.
--
-- Старые строки не трогаем: они уже есть, и удалять их должен человек,
-- когда решит, что разбирать нечего.

create or replace function reject_unnamed_sighting()
returns trigger
language plpgsql
as $$
begin
  if new.animal_id is null then
    raise exception
      'Встреча без животного не записывается. Заведите животное '
      'в разделе «Животные» и загрузите эталонные снимки.';
  end if;
  return new;
end;
$$;

drop trigger if exists sightings_require_animal on sightings;
create trigger sightings_require_animal
  before insert on sightings
  for each row execute function reject_unnamed_sighting();

