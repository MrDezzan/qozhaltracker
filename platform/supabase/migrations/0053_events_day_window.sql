-- Суточные показатели считались по последним 200 событиям
--
-- На экране фермы стоят подписи «за сутки»: время у кормушек, подходы по
-- часам, максимум голов. Считались они по выборке `getRecentEvents`,
-- которая брала 200 последних событий независимо от времени. На тихой
-- ферме это и были примерно сутки, а на ферме с пятью камерами 200
-- событий набегает за двадцать минут — и «время у кормушек за сутки»
-- показывало двадцать минут.
--
-- Теперь суточные показатели берутся запросом по окну времени. Чтобы он
-- не читал таблицу целиком, нужен составной индекс: по ферме и по
-- времени сразу. Отдельные индексы по farm_id и по occurred_at здесь не
-- помогают — планировщик выберет один из них и отфильтрует остальное
-- перебором.

create index if not exists events_farm_occurred_idx
  on events (farm_id, occurred_at desc);
