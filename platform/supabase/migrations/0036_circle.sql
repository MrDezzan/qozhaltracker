-- ---------------------------------------------------------------------------
-- Одно движение по кругу вместо четырёх отдельных команд
-- ---------------------------------------------------------------------------
-- Четыре шага — «мимо камеры», «в обратную сторону», «навстречу», «от
-- камеры» — оказались лишним усложнением. Человек всё равно делает одно
-- непрерывное движение: обводит животное кругом. Разбивать это на
-- команды значит заставлять его останавливаться и ждать, пока система
-- переключит шаг.
--
-- Теперь просьба одна: провести животное вокруг. Кадры набираются
-- подряд, а разными их делает то же правило, что и раньше, — новый кадр
-- берётся, только если он не похож на уже записанные.
--
-- Пометка ракурса никуда не делась: устройство ставит её, когда сумело
-- разобрать. Просто она больше не управляет ходом записи, а остаётся
-- сведением о кадре. Это и была ошибка прошлой версии — сделать
-- распознавание ракурса УСЛОВИЕМ продвижения, хотя оно молчит чаще, чем
-- говорит.

create or replace function views_for_camera(target_camera_id uuid)
returns text[]
language sql
immutable
set search_path = public
as $$
  -- Пусто для всех камер: шагов по ракурсам больше нет.
  --
  -- Функция оставлена, а не удалена, потому что на неё ссылается
  -- start_recording, и потому что порядок ракурсов может понадобиться
  -- снова — например, если появится модель поз для скота и ракурс
  -- станет определяться надёжно.
  select '{}'::text[]
$$;

-- Идущие сеансы переводим на новый лад: без шагов, до потолка кадров
update enrollment_sessions
   set views_order = '{}'
 where status = 'recording';

-- ---------------------------------------------------------------------------
-- Сколько кадров нужно
-- ---------------------------------------------------------------------------
-- За круг животное показывает все стороны, и кадров набирается быстро.
-- Двадцать — то же число, что и раньше; двенадцать из них человек видит
-- как сто процентов, остальные добираются молча, пока оно ещё в кадре.

alter table enrollment_sessions
  alter column needed set default 12,
  alter column target set default 20;
