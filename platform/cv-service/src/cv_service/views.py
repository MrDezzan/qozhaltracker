"""
Какой ракурс животного сейчас перед камерой.

Без модели поз — её для скота не существует. По двум признакам, которые
камера видит всегда: форме рамки и направлению движения.

    Вытянутая рамка + движение поперёк кадра  → бок
    Компактная рамка + рамка растёт           → животное идёт на камеру
    Компактная рамка + рамка уменьшается      → уходит от камеры

Три вещи, которые здесь сделаны намеренно и без которых всё разваливается.

**Мёртвая зона между «вытянутый» и «компактный».** Между порогами
специально оставлен зазор, и промежуточные значения не относятся никуда.
Животное, повёрнутое вполоборота, не бок и не перед — назвать его любым
из двух значило бы записать эталон под неверной пометкой, а пометка
потом участвует в узнавании.

**Ракурс объявляется по времени, а не по кадру.** Одиночный кадр ничего
не значит: животное мотнуло головой, трекер дёрнул рамку. Ракурс должен
продержаться полторы секунды подряд.

**Разрыв обнуляет накопленное.** Животное вышло из кадра и вернулось —
это уже другой заход, и склеивать его с прежним нельзя: между двумя
точками оно могло развернуться.

Чего этот модуль НЕ утверждает: какой бок левый, а какой правый. Это
зависит от того, как повешена камера, и системе неизвестно. Она
различает два РАЗНЫХ бока — для узнавания важно именно это.
"""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass, field

# Названия ракурсов. Совпадают со значениями колонки `view` в базе
SIDE_A = "side_a"
SIDE_B = "side_b"
FRONT = "front"
REAR = "rear"

ALL_VIEWS = (SIDE_A, SIDE_B, FRONT, REAR)

VIEW_TITLES = {
    SIDE_A: "мимо камеры",
    SIDE_B: "в обратную сторону",
    FRONT: "навстречу камере",
    REAR: "от камеры",
}

# ---------------------------------------------------------------------------
# Пороги
# ---------------------------------------------------------------------------

# Отношение ширины рамки к высоте. Корова сбоку — примерно два к одному,
# в лоб — около одного. Между порогами оставлена мёртвая зона: то, что
# попало в неё, не относится никуда
SIDE_RATIO = 1.8
COMPACT_RATIO = 1.3

# Насколько быстро точка опоры должна ехать поперёк кадра, чтобы это
# считалось движением. В долях ширины самого животного за секунду —
# так порог не зависит ни от разрешения, ни от того, далеко ли оно
MIN_SPEED = 0.25

# Насколько быстро должна меняться площадь рамки, чтобы считать, что
# животное приближается или удаляется. Доля площади за секунду
MIN_GROWTH = 0.12

# Сколько ракурс должен продержаться, прежде чем объявить его
HOLD_S = 1.5

# Перерыв, после которого накопленное по треку выбрасывается.
#
# КОРОЧЕ выдержки, и это принципиально. Ракурс считается по первой и
# последней точке окна; если животное на секунду скрылось за столбом и
# появилось дальше, в окне окажутся точки по обе стороны от пропажи, а
# между ними — скачок, которого никто не наблюдал. Система объявит
# уверенное движение вбок по перемещению, которого не видела.
#
# Порог длиннее выдержки был бы почти бесполезен: окно и так выбрасывает
# всё старше полутора секунд, и разрыв такой длины обнуляет отсчёт сам
# собой. Работу делает именно короткий порог.
GAP_S = 0.8


@dataclass
class _Point:
    at: float
    x: float
    y: float
    width: float
    height: float

    @property
    def area(self) -> float:
        return self.width * self.height

    @property
    def ratio(self) -> float:
        return self.width / self.height if self.height > 0 else 0.0


def _foot(bbox: tuple[float, float, float, float]) -> tuple[float, float]:
    """Точка опоры: середина нижней грани рамки."""
    x1, _, x2, y2 = bbox
    return ((x1 + x2) / 2.0, y2)


def guess(first: _Point, last: _Point) -> str | None:
    """
    Ракурс по паре наблюдений. None — сказать нечего.

    Отдельной функцией, чтобы её можно было проверить на выдуманных
    траекториях, не поднимая ни камеры, ни модели.
    """
    seconds = last.at - first.at
    if seconds <= 0:
        return None

    # Форма берётся по последнему наблюдению, а не по среднему:
    # животное поворачивается, и важно, как оно стоит сейчас
    ratio = last.ratio
    if ratio <= 0:
        return None

    if ratio >= SIDE_RATIO:
        # Скорость в долях ширины животного за секунду
        speed = (last.x - first.x) / max(1.0, last.width) / seconds
        if abs(speed) < MIN_SPEED:
            # Вытянутое, но стоит: бок это или нет — сказать нельзя
            return None
        return SIDE_A if speed > 0 else SIDE_B

    if ratio <= COMPACT_RATIO:
        if first.area <= 0:
            return None
        growth = (last.area - first.area) / first.area / seconds
        if abs(growth) < MIN_GROWTH:
            return None
        return FRONT if growth > 0 else REAR

    # Мёртвая зона: вполоборота. Намеренно ничего не возвращаем
    return None


@dataclass
class _Track:
    points: deque = field(default_factory=lambda: deque(maxlen=64))
    # С какого момента держится нынешний ракурс. None — ракурса нет
    holding: str | None = None
    holding_since: float | None = None

    def reset(self) -> None:
        self.points.clear()
        self.holding = None
        self.holding_since = None


@dataclass
class ViewEstimator:
    """
    Копит наблюдения по трекам и говорит, какой ракурс подтверждён.

    Состояние по каждому треку своё: в кадре может быть несколько
    животных, и мерить им общее направление было бы бессмыслицей.
    """

    hold_s: float = HOLD_S
    _tracks: dict[int, _Track] = field(default_factory=dict)

    def observe(
        self, track_id: int, bbox: tuple[float, float, float, float], now: float
    ) -> str | None:
        """
        Добавляет наблюдение и возвращает ПОДТВЕРЖДЁННЫЙ ракурс.

        None означает «пока сказать нечего» — это обычный ответ, а не
        сбой: большую часть времени животное поворачивается, и ракурса
        у него нет.
        """
        track = self._tracks.setdefault(track_id, _Track())

        if track.points and now - track.points[-1].at > GAP_S:
            # Животное уходило из кадра. Между двумя точками оно могло
            # развернуться, и склеивать их нельзя
            track.reset()

        x1, y1, x2, y2 = bbox
        x, y = _foot(bbox)
        track.points.append(
            _Point(at=now, x=x, y=y, width=x2 - x1, height=y2 - y1)
        )

        current = self._current(track, now)

        if current is None or current != track.holding:
            track.holding = current
            track.holding_since = now if current is not None else None
            return None

        if track.holding_since is None:
            track.holding_since = now
            return None

        if now - track.holding_since < self.hold_s:
            return None

        return current

    def _current(self, track: _Track, now: float) -> str | None:
        """Ракурс по накопленному окну. Окно — последние полторы секунды."""
        window = [p for p in track.points if now - p.at <= self.hold_s]
        if len(window) < 2:
            return None
        return guess(window[0], window[-1])

    def forget(self, track_id: int) -> None:
        self._tracks.pop(track_id, None)

    def tracked(self) -> set[int]:
        return set(self._tracks)


# ---------------------------------------------------------------------------
# Порядок ракурсов зависит от того, что камера способна показать
# ---------------------------------------------------------------------------
# Просить у камеры то, чего она не покажет, — верный способ загнать
# человека в тупик: он будет крутить животное, а счётчик стоять.

def order_for(placement: str | None, has_feeder_zone: bool = False) -> tuple[str, ...]:
    """
    Какие ракурсы и в каком порядке просить у этой камеры.

    Пустой список означает «ракурсы не различаем»: запись идёт как
    раньше, просто разными положениями.
    """
    if placement == "overhead":
        # Сверху всегда одна и та же спина. Что бы животное ни делало,
        # другой ракурс с этой камеры не появится
        return ()

    if has_feeder_zone:
        # У кормушки животное стоит мордой к корму — иначе оно не ест.
        # Поэтому перед идёт первым: он там берётся сразу
        return (FRONT, SIDE_A, SIDE_B, REAR)

    # Сбоку от прохода. Бока первыми: они определяются надёжнее всего —
    # два согласных признака против одного у переда с задом, — и дают
    # больше всего для узнавания. Бросят запись на середине — останется
    # самое ценное
    return (SIDE_A, SIDE_B, FRONT, REAR)


def feeder_view(inside_feeder: bool, moving: bool) -> str | None:
    """
    Ракурс у кормушки, когда движения нет.

    Здесь «перед» не определяется, а ВЫВОДИТСЯ: животное стоит в зоне
    кормушки, значит стоит к ней мордой. Это допущение, а не наблюдение,
    и держится оно на разметке зоны — не размечена, ответа нет.

    Как только животное пошло, допущение снимается: подходя и отходя,
    оно показывает бока, и их определяет обычный способ.
    """
    if not inside_feeder or moving:
        return None
    return FRONT


