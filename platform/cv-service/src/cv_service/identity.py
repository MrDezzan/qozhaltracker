"""
Кого как зовут: разбор ответов поиска и раздача кличек по всему кадру.

Чистая логика. Ни базы, ни сети, ни модели — поэтому проверяется целиком
и мутациями, а это здесь важнее обычного: ошибка узнавания не падает с
исключением, она просто пишет чужую кличку, и заметить её можно только
глазами по видео.

ЗАЧЕМ ЭТО ПОЯВИЛОСЬ

Кличка раздавалась по одному кропу за раз: посчитали вектор, спросили
базу, записали `track_animals[track_id] = animal_id`. Проверки, занята
ли эта кличка другим треком В ЭТОМ ЖЕ КАДРЕ, не было вообще.

То есть две коровы, стоящие рядом, могли обе стать «Зорькой». Это не
неточность, а невозможное состояние: одно животное не может быть в двух
местах сразу. На дашборде оно выглядит не как ошибка узнавания, а как
загадка — Зорька прошла мимо камеры дважды за одну секунду.

Лечится тем, что решение принимается СРАЗУ ПРО ВЕСЬ КАДР: у каждой
клички ровно один трек, у каждого трека ровно одна кличка.

ОТКУДА ВЗЯТО

Из `cvar-vision-dl/remind-reid-tracker` (MIT): глобальное назначение
венгерским алгоритмом, замки на очевидных парах и колонка «это новый».
Само сравнение векторов у нас своё — MegaDescriptor обучен на животных,
и менять его на их DINOv3 незачем.

ЧЕМ ОТЛИЧАЕТСЯ ОТРЫВ

У них отрыв считается между первым и вторым кандидатом одного
наблюдения. Здесь — между лучшим назначением по кадру и лучшим
назначением БЕЗ этой пары. Разница видна на таком кадре:

    трек A: Зорька 0.20, Ночка 0.50
    трек B: Зорька 0.30, Ночка 0.32

По-старому трек B спорный: 0.32 против 0.30, отрыв 0.02. По кадру
целиком спора нет: если B отдать Зорьку, то A достаётся Ночка за 0.50,
и всё назначение дорожает на 0.28. Зорьку заберёт A, Ночку — B, и обе
клички названы уверенно.

ДВА ВОПРОСА, И ИХ НЕЛЬЗЯ ПУТАТЬ

«Совпадение ли это вообще» решает ПОРОГ. «Тот ли это из нескольких»
решает ОТРЫВ. Поэтому отрыв считается только против других кандидатов,
а не против отказа называть: иначе он втихую ужесточал бы порог на свою
величину, а на ферме с одним заведённым животным не узнавал бы никого —
сравнивать там не с кем по определению.
"""

from __future__ import annotations

from dataclasses import dataclass

# Три исхода, и сводить их к двум нельзя. «Спорно» — это не «не узнали»:
# при «не узнали» животное незнакомое и его надо заводить, при «спорно»
# оно как раз знакомое, просто похожих сразу несколько, и заводить новую
# запись тут — худшее из возможного
STRONG = "уверенно"
AMBIGUOUS = "спорно"
WEAK = "не узнан"


@dataclass(frozen=True)
class Candidate:
    """Один ответ поиска: кто и насколько далеко."""

    animal_id: str
    distance: float


@dataclass(frozen=True)
class Seen:
    """
    Что поиск сказал про один кроп.

    `candidates` — по возрастанию расстояния, как их отдаёт база.
    """

    track_id: int
    candidates: tuple[Candidate, ...] = ()
    # Насколько кадру можно верить, от 0 до 1. Единица — идеальный
    # кадр; на плохом с того же отрыва спрашивается строже
    quality: float = 1.0


@dataclass(frozen=True)
class Verdict:
    """Решение по одному треку."""

    track_id: int
    animal_id: str = ""
    quality: str = WEAK
    distance: float | None = None
    # Насколько дороже обошёлся бы кадр без этой пары. Пусто — считать
    # было не с чем
    margin: float | None = None
    reason: str = ""

    @property
    def named(self) -> bool:
        return bool(self.animal_id) and self.quality == STRONG


# Стоимость колонки «это новый, не называем».
#
# Равна порогу, и это не выбор из удобства: всё, что дальше порога,
# по определению не совпадение. Значит, назначение дороже порога хуже,
# чем отказ назвать, — и венгерский алгоритм выберет отказ сам, без
# отдельной проверки после.
def dummy_cost(threshold: float) -> float:
    return float(threshold)


def solve(cost: list[list[float]]) -> list[tuple[int, int]]:
    """
    Венгерский алгоритм: раздать строки по столбцам с наименьшей суммой.

    Вынесен отдельной функцией с одной целью — чтобы `assign` можно было
    читать, не отвлекаясь на то, откуда взялся scipy. Матрица тут
    крошечная: животных в кадре редко больше двадцати.
    """
    from scipy.optimize import linear_sum_assignment

    if not cost or not cost[0]:
        return []
    rows, cols = linear_sum_assignment(cost)
    return list(zip(rows.tolist(), cols.tolist()))


# Цена запрещённой клетки. Не бесконечность: с бесконечностями
# венгерский алгоритм считает задачу неразрешимой и падает, а нам нужно,
# чтобы он просто обошёл такую пару стороной
def _forbidden_cost(threshold: float) -> float:
    return dummy_cost(threshold) * 10.0


def _cost_matrix(
    seen: list[Seen],
    animals: list[str],
    threshold: float,
    forbidden: tuple[int, int] | None = None,
    must_name: int | None = None,
) -> list[list[float]]:
    """
    Матрица «трек × животное», справа — по колонке «новый» на каждый трек.

    Отдельных колонок «новый» ровно столько, сколько треков: одной на
    всех не хватило бы, а незнакомых животных в кадре может быть сколько
    угодно.

    Колонки «новый» ОБЕЗЛИЧЕНЫ: они одинаковы для всех треков, и важно
    только их число. Сначала каждому треку полагалась своя, и мутант
    «чужая колонка доступна любому» пережил все тесты — правильно
    пережил: колонок ровно столько же, сколько треков, разобрать больше
    одной на трек всё равно нельзя, и решение не менялось. Различие,
    которое ни на что не влияет, из кода убрано.

    `must_name` — треку, для которого считаем отрыв, отказ запрещён.
    Иначе отрыв отвечал бы не на тот вопрос: не «насколько этот кандидат
    лучше следующего», а «насколько он лучше молчания». Второе уже
    проверено порогом, и мерить его второй раз значит отбрасывать
    верные совпадения впритык к порогу.

    Кандидаты дальше порога сюда не доходят — их отсекает `assign` до
    построения матрицы. Второй такой проверки здесь не было и быть не
    должно: две проверки одного правила расходятся молча.
    """
    запрет = _forbidden_cost(threshold)
    отказ = dummy_cost(threshold)
    матрица: list[list[float]] = []

    for i, наблюдение in enumerate(seen):
        расстояния = {c.animal_id: c.distance for c in наблюдение.candidates}
        строка = []
        for j, животное in enumerate(animals):
            цена = расстояния.get(животное)
            if цена is None or forbidden == (i, j):
                строка.append(запрет)
            else:
                строка.append(float(цена))

        отказ_этому = запрет if i == must_name else отказ
        строка += [отказ_этому] * len(seen)
        матрица.append(строка)

    return матрица


def _total(cost: list[list[float]], pairs: list[tuple[int, int]]) -> float:
    return sum(cost[i][j] for i, j in pairs)


def _gap(
    seen: list[Seen],
    animals: list[str],
    threshold: float,
    row: int,
    col: int,
    best_total: float,
) -> float:
    """
    Насколько дороже обошёлся бы кадр, запрети мы эту пару.

    Это и есть отрыв. Считается по кадру целиком, поэтому учитывает
    соседей: кандидат, спорный сам по себе, перестаёт быть спорным, если
    другого претендента на ту же кличку кто-то забирает дороже.

    Сравниваем с назначением, где трек ВСЁ РАВНО назван, — отказ ему
    запрещён. Когда назвать больше некем, отрыва нет вовсе: это не
    «кандидат сомнительный», а «сравнивать не с чем», и такое
    совпадение принимается, раз оно прошло порог.
    """
    без_пары = _cost_matrix(
        seen, animals, threshold, forbidden=(row, col), must_name=row
    )
    решение = solve(без_пары)
    другой = _total(без_пары, решение)

    # Запрет стоит дороже всего на свете: если он попал в решение,
    # назвать этот трек было больше некем
    if другой >= _forbidden_cost(threshold):
        return float("inf")

    return другой - best_total


def assign(
    seen: list[Seen],
    threshold: float,
    min_margin: float,
    taken: dict[str, int] | None = None,
) -> list[Verdict]:
    """
    Раздать клички всем трекам кадра разом.

    `taken` — кличка → трек, за которым она уже закреплена с прошлых
    кадров. Своему треку она не мешает, чужому недоступна: животное,
    которое сейчас видно вон там, не может оказаться ещё и здесь.

    Возвращает по решению на каждый трек, в том же порядке.
    """
    занято = taken or {}
    if not seen:
        return []

    # Кандидаты, закреплённые за ЧУЖИМ треком, выбывают сразу
    очищенные = [
        Seen(
            track_id=s.track_id,
            quality=s.quality,
            candidates=tuple(
                c
                for c in s.candidates
                if занято.get(c.animal_id, s.track_id) == s.track_id
                and c.distance <= threshold
            ),
        )
        for s in seen
    ]

    животные = sorted({c.animal_id for s in очищенные for c in s.candidates})
    if not животные:
        return [
            Verdict(track_id=s.track_id, quality=WEAK, reason="похожих нет")
            for s in seen
        ]

    цена = _cost_matrix(очищенные, животные, threshold)
    лучшее = solve(цена)
    сумма = _total(цена, лучшее)

    решения: list[Verdict] = []
    for i, наблюдение in enumerate(очищенные):
        назначено = next((j for r, j in лучшее if r == i), None)

        if назначено is None or назначено >= len(животные):
            ближайший = min(
                (c.distance for c in наблюдение.candidates), default=None
            )
            решения.append(
                Verdict(
                    track_id=наблюдение.track_id,
                    quality=WEAK,
                    distance=ближайший,
                    reason="ближе порога никого не нашлось",
                )
            )
            continue

        животное = животные[назначено]
        расстояние = цена[i][назначено]
        отрыв = _gap(очищенные, животные, threshold, i, назначено, сумма)
        нужно = margin_needed(min_margin, наблюдение.quality)

        if отрыв < нужно:
            решения.append(
                Verdict(
                    track_id=наблюдение.track_id,
                    quality=AMBIGUOUS,
                    animal_id="",
                    distance=расстояние,
                    margin=отрыв,
                    reason=(
                        f"похож ещё кто-то, разница всего {отрыв:.3f} "
                        f"при нужных {нужно:.3f}"
                    ),
                )
            )
            continue

        решения.append(
            Verdict(
                track_id=наблюдение.track_id,
                animal_id=животное,
                quality=STRONG,
                distance=расстояние,
                margin=отрыв,
                reason="",
            )
        )

    return решения


# ------------------------------------------------- качество как вес
#
# Кадр бывает разный, а порог отрыва до сих пор был один на все.
#
# Смазанная мелкая корова даёт шумный вектор: расстояния до эталонов
# у него все примерно одинаковые и все примерно случайные. Отрыв 0.06
# на чётком крупном кадре — это разница между животными. Тот же отрыв
# на смазанном — это разница между двумя шумами.
#
# Отсекать плохие кадры целиком нельзя: животное могло всю дорогу идти
# быстро, и тогда чётких кадров нет вовсе, а узнать его всё равно надо.
# Поэтому плохой кадр не отбрасывается, а обязан доказывать больше.
#
# Идея из REMIND (quality-weighted score): у них качество взвешивает
# каналы признаков. Канал у нас один, взвешивать нечего — но требование
# к отрыву качеством масштабируется ровно так же.

# Во сколько раз строже отрыв на совсем негодном кадре
QUALITY_PENALTY = 2.0

# Площадь, выше которой животное видно во всех подробностях. Примерно
# 200×200 точек — та же величина, с которой заводится новая особь
GOOD_AREA_PX = 40_000.0


def crop_quality(area: float, confidence: float, clarity: float) -> float:
    """
    Насколько кадру можно верить, от 0 до 1.

    Три множителя, и каждый может обнулить остальные: далёкое животное
    не спасёт резкость, смазанное — размер, а неуверенная детекция может
    оказаться и не животным.
    """
    видно = min(1.0, max(0.0, area) / GOOD_AREA_PX)
    return видно * min(1.0, max(0.0, confidence)) * min(1.0, max(0.0, clarity))


def margin_needed(base: float, quality: float) -> float:
    """
    Какой отрыв требовать от кадра такого качества.

    На идеальном кадре — обычный. На никаком — вдвое больше.
    """
    испорчено = 1.0 - min(1.0, max(0.0, quality))
    return base * (1.0 + испорчено * (QUALITY_PENALTY - 1.0))


# ------------------------------------------------------------- память
#
# Узнали животное — стоит ли запоминать этот кадр как ещё один эталон.
#
# Раньше запоминался КАЖДЫЙ, и это две беды сразу.
#
# Первая: эталонов у животного двенадцать, и вытесняется самый старый.
# Корова, которую десять раз подряд сняли с одного ракурса, вытеснила
# сама себя: в банке остались десять почти одинаковых спин, а профиль,
# снятый когда-то сбоку, ушёл. Узнавание сбоку пропало — и выглядит это
# как «сначала работало, потом перестало».
#
# Вторая: запоминалось и то, что узналось с переспроса, то есть с
# сомнением. Ошибка узнавания живёт секунду, ошибка в эталоне — вечно:
# дальше под этот эталон подходит не то животное, и чем дальше, тем
# увереннее.
#
# Отсюда правило из REMIND: учимся только на уверенных совпадениях, и
# только тому, чего ещё не знаем.

# Ближе этого — тот же самый ракурс, второй раз его хранить незачем.
#
# У REMIND это порог «дубликата» по косинусной близости 0.92; у нас в
# ходу расстояние, то есть 0.08. Число не подгоняется: оно означает
# «отличается меньше, чем два кадра одного прохода мимо камеры».
DUP_DISTANCE = 0.08


def worth_remembering(
    verdict: Verdict,
    crop_ok: bool = True,
    voted: bool = False,
) -> tuple[bool, str]:
    """
    Класть ли этот кадр в эталоны животного.

    Возвращает решение и причину. Причина возвращается всегда, даже при
    отказе: «эталон не добавлен» без объяснения выглядит поломкой, а
    отказ здесь — обычное дело и происходит чаще, чем согласие.
    """
    if verdict.quality != STRONG or not verdict.animal_id:
        return False, "узнали неуверенно"
    if voted:
        # Совпадение, добытое переспросом: два кадра сошлись, и этого
        # хватает, чтобы показать кличку. Для эталона — нет. Показанная
        # кличка живёт секунду, эталон живёт всегда
        return False, "узнали с переспроса, для эталона этого мало"
    if not crop_ok:
        return False, "кадр слишком плох для эталона"
    if verdict.distance is not None and verdict.distance < DUP_DISTANCE:
        return False, f"такой ракурс уже есть (расстояние {verdict.distance:.3f})"
    return True, "новый ракурс"


# ------------------------------------------------- заводить ли новую
#
# Полоса «почти узнали» за порогом.
#
# Расстояние 0.40 при пороге 0.35 — это не «незнакомое животное». Это
# чаще всего ЗНАКОМОЕ, снятое непривычно: сзади, в темноте, наполовину
# за столбом. Завести по такому кадру новую запись значит своими руками
# сделать двойника, а двойник хуже пропуска: кандидатов становится
# больше, отрыв между ними меньше, и система постепенно перестаёт
# узнавать вообще кого-либо.
#
# Поэтому в этой полосе новую запись не заводим сразу, а требуем больше
# подтверждений. Идея из REMIND — provisional_new: сомнительное
# создание откладывается и копит доказательства.
NEAR_MISS = 0.10

# Во сколько раз больше подтверждений нужно в этой полосе
NEAR_MISS_PATIENCE = 3


def sightings_needed(nearest: float | None, threshold: float, base: int) -> int:
    """
    Сколько раз надо увидеть незнакомца, прежде чем заводить запись.

    Обычно `base`. В полосе «почти узнали» — втрое больше: цена ошибки
    здесь не «не завели», а «завели двойника навсегда».
    """
    if nearest is None:
        return base
    if threshold < nearest <= threshold + NEAR_MISS:
        return base * NEAR_MISS_PATIENCE
    return base


def why_patient(nearest: float | None, threshold: float) -> str:
    """Объяснение для журнала. Пусто — обычный случай."""
    if nearest is not None and threshold < nearest <= threshold + NEAR_MISS:
        return (
            f"почти похож на заведённого ({nearest:.3f} при пороге "
            f"{threshold:.2f}) — не тороплюсь заводить двойника"
        )
    return ""


def candidate_of(verdict: Verdict, seen: Seen) -> str:
    """
    Кто был ближайшим, даже когда назвать не решились.

    Нужно переспросу: спорный трек не отбрасывается, а запоминает
    ближайшего и спрашивает ещё раз по другому кадру.
    """
    if verdict.animal_id:
        return verdict.animal_id
    return seen.candidates[0].animal_id if seen.candidates else ""
