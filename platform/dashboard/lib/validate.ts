/**
 * Проверки входящих значений.
 *
 * Отдельной библиотеки здесь нет намеренно: проверок мало, они простые,
 * и каждая нужна ровно в одном виде. Zod добавил бы зависимость и слой,
 * который пришлось бы держать в голове, ради десятка строк.
 *
 * Правило, ради которого файл существует: **идентификатор, пришедший из
 * формы или из адреса, до запроса в базу должен быть проверен.** Строка
 * вроде `' or 1=1--` до Postgres всё равно не доедет — запросы идут
 * параметрами, — но попадёт в журнал, в сообщение об ошибке и в чужие
 * глаза. Дешевле отказать сразу.
 */

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** Похоже ли значение на uuid версии 1–8. */
export function этоUuid(значение: unknown): значение is string {
  return typeof значение === "string" && UUID.test(значение);
}

/**
 * Строка из формы: обрезана, не длиннее предела, не пустая при требовании.
 *
 * Возвращает `null`, если значение не годится. Вызывающий сам решает,
 * что показать человеку: сообщения об ошибках живут рядом с формой, а не
 * здесь, иначе они разъедутся с тем, что написано на экране.
 */
export function строка(
  значение: unknown,
  { максимум, обязательна = true }: { максимум: number; обязательна?: boolean }
): string | null {
  if (typeof значение !== "string") return null;
  const v = значение.trim();
  if (обязательна && v.length === 0) return null;
  if (v.length > максимум) return null;
  return v;
}

/** Значение из заранее известного набора. Всё остальное — отказ. */
export function изСписка<T extends string>(
  значение: unknown,
  разрешённые: readonly T[]
): T | null {
  return typeof значение === "string" && (разрешённые as readonly string[]).includes(значение)
    ? (значение as T)
    : null;
}

/** Целое число в диапазоне включительно. */
export function целое(
  значение: unknown,
  { от, до }: { от: number; до: number }
): number | null {
  const n = typeof значение === "number" ? значение : Number(String(значение ?? "").trim());
  if (!Number.isInteger(n) || n < от || n > до) return null;
  return n;
}

/**
 * Время вида ЧЧ:ММ.
 *
 * Прежняя проверка была `^\d{2}:\d{2}$`, и «99:99» проходила её целиком,
 * а падала уже в Postgres на колонке типа `time` — с сырым текстом
 * ошибки наружу. Диапазоны проверяются здесь.
 */
export function времяСуток(значение: unknown): string | null {
  if (typeof значение !== "string") return null;
  const m = значение.trim().match(/^(\d{2}):(\d{2})$/);
  if (!m) return null;
  const часы = Number(m[1]);
  const минуты = Number(m[2]);
  if (часы > 23 || минуты > 59) return null;
  return `${m[1]}:${m[2]}`;
}
