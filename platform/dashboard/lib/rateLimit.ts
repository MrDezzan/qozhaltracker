/**
 * ОГРАНИЧЕНИЕ ЧАСТОТЫ ЗАПРОСОВ
 *
 * Счётчик живёт в памяти процесса. Это сознательный выбор, и у него есть
 * граница применимости, о которой надо знать заранее.
 *
 * При нескольких экземплярах приложения у каждого будет свой счётчик, и
 * фактический предел умножится на их число. Для того, ради чего лимит
 * здесь стоит — не дать одному вошедшему пользователю превратить наш
 * сервер в сканер чужой сети и не дать тяжёлому запросу крутиться в
 * цикле, — этого достаточно: множитель на два-три не меняет сути.
 *
 * Чего в памяти делать нельзя: считать попытки входа. Там счётчик
 * обязан быть общим, иначе перебор просто раскидывается по экземплярам.
 * Вход у нас идёт напрямую в Supabase Auth из браузера, и ограничение
 * частоты там своё — поэтому этот случай сюда и не попал.
 *
 * Если экземпляров станет много, замена — общее хранилище (Redis,
 * Upstash) с тем же самым внешним видом функции `проверитьЧастоту`.
 * Вызывающий код менять не придётся.
 *
 * Почему здесь НЕТ `import "server-only"`, хотя напрашивается. Модуль
 * используется в `app/alertActions.ts`, а оттуда клиентский компонент
 * `LiveCamera` импортирует серверное действие. `server-only` бросает
 * исключение на всю цепочку импорта — приложение падало на сборке
 * клиентского пакета. Секретов модуль не хранит: это счётчик в памяти,
 * на клиенте он просто бесполезен.
 */

type Окно = { счёт: number; доТого: number };

const окна = new Map<string, Окно>();

/**
 * Чистка раз в минуту, а не по таймеру.
 *
 * setInterval в серверном модуле Next.js живёт дольше, чем ожидаешь, и
 * держит процесс. Проще подмести на входе: записей мало, проход дешёвый.
 */
let последняяЧистка = 0;

function подмести(сейчас: number) {
  if (сейчас - последняяЧистка < 60_000) return;
  последняяЧистка = сейчас;
  for (const [ключ, окно] of окна) {
    if (окно.доТого <= сейчас) окна.delete(ключ);
  }
}

export type Итог = { можно: true } | { можно: false; черезСекунд: number };

/**
 * @param ключ   кто и что делает: "stream:<userId>", "frame:<cameraId>"
 * @param предел сколько обращений разрешено в окне
 * @param окноМс длина окна
 */
export function проверитьЧастоту(
  ключ: string,
  предел: number,
  окноМс: number,
  сейчас: number = Date.now()
): Итог {
  подмести(сейчас);

  const текущее = окна.get(ключ);
  if (!текущее || текущее.доТого <= сейчас) {
    окна.set(ключ, { счёт: 1, доТого: сейчас + окноМс });
    return { можно: true };
  }

  if (текущее.счёт < предел) {
    текущее.счёт += 1;
    return { можно: true };
  }

  return {
    можно: false,
    черезСекунд: Math.max(1, Math.ceil((текущее.доТого - сейчас) / 1000)),
  };
}

/** Только для тестов: обнулить состояние между проверками. */
export function сброситьЧастоту(): void {
  окна.clear();
  последняяЧистка = 0;
}

/**
 * Ответ 429 с заголовком Retry-After.
 *
 * Тело без подробностей: сколько именно осталось попыток — сведения для
 * того, кто подбирает, а не для того, кто работает.
 */
export function слишкомЧасто(черезСекунд: number): Response {
  return new Response("Слишком часто", {
    status: 429,
    headers: {
      "Retry-After": String(черезСекунд),
      "Cache-Control": "no-store",
    },
  });
}
