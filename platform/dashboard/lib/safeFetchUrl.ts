import { lookup } from "node:dns/promises";
import "server-only";

/**
 * ПРОВЕРКА АДРЕСА ПЕРЕД ИСХОДЯЩИМ ЗАПРОСОМ
 *
 * Адрес потока камеры пишет в базу владелец фермы. Сервер потом ходит по
 * нему сам и отдаёт ответ в браузер. Без проверки это готовый SSRF:
 * владелец ставит своей камере адрес служебной сети облака и получает
 * ответ оттуда через наш же сервер, с нашими правами в сети.
 *
 * Проверяется не строка, а то, куда имя на самом деле разрешается:
 * `http://внутренний.example.com` выглядит безобидно, а указывает на
 * 10.0.0.1. Поэтому сначала разбирается схема и порт, потом имя
 * резолвится, и только после этого адрес считается годным.
 *
 * Проверка вызывается дважды, и это не лишнее:
 *   при записи адреса — чтобы человек сразу увидел отказ;
 *   перед самим запросом — потому что между записью и запросом запись в
 *   DNS могла поменяться (DNS rebinding).
 */

export const ПРИЧИНА = {
  схема: "Разрешены только http и https",
  порт: "Такой порт использовать нельзя",
  имя: "Имя узла не разрешается в адрес",
  внутренний: "Адрес ведёт во внутреннюю сеть",
} as const;

export type Причина = (typeof ПРИЧИНА)[keyof typeof ПРИЧИНА];

export type Проверка =
  | { ok: true; url: URL; адреса: string[] }
  | { ok: false; причина: Причина };

/**
 * Порты, по которым в локальной сети чаще всего сидит что-то, чего
 * пользователю видеть не положено. Список короткий намеренно: запрещать
 * всё, кроме 80 и 443, нельзя — камеры живут на 554, 8080, 8554 и прочих.
 */
const ЗАПРЕЩЁННЫЕ_ПОРТЫ = new Set([22, 23, 25, 445, 3306, 5432, 6379, 9200, 11211, 27017]);

/** Разбирает адрес и проверяет схему и порт. Сеть здесь не трогается. */
export function разобратьАдрес(значение: string): Проверка {
  let url: URL;
  try {
    url = new URL(значение);
  } catch {
    return { ok: false, причина: ПРИЧИНА.схема };
  }

  if (url.protocol !== "http:" && url.protocol !== "https:") {
    return { ok: false, причина: ПРИЧИНА.схема };
  }

  const порт = url.port ? Number(url.port) : url.protocol === "https:" ? 443 : 80;
  if (!Number.isInteger(порт) || порт < 1 || порт > 65535) {
    return { ok: false, причина: ПРИЧИНА.порт };
  }
  if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.has(порт)) {
    return { ok: false, причина: ПРИЧИНА.порт };
  }

  return { ok: true, url, адреса: [] };
}

/**
 * Внутренний ли это адрес.
 *
 * Отдельная функция с явным перечислением диапазонов, а не регулярное
 * выражение: диапазоны здесь видно глазами, и каждый подписан.
 */
export function внутреннийАдрес(адрес: string): boolean {
  // IPv6
  if (адрес.includes(":")) {
    const a = адрес.toLowerCase();
    if (a === "::" || a === "::1") return true;          // неопределённый и петля
    if (a.startsWith("fe80")) return true;                 // link-local
    if (a.startsWith("fc") || a.startsWith("fd")) return true; // unique local
    // ::ffff:10.0.0.1 — IPv4 внутри IPv6
    const m = a.match(/::ffff:(\d+\.\d+\.\d+\.\d+)$/);
    if (m) return внутреннийАдрес(m[1]);
    return false;
  }

  const ч = адрес.split(".").map(Number);
  if (ч.length !== 4 || ч.some((x) => !Number.isInteger(x) || x < 0 || x > 255)) {
    return true; // не разобрали — считаем опасным
  }
  const [a, b] = ч;

  if (a === 0) return true;                      // 0.0.0.0/8
  if (a === 10) return true;                     // частная
  if (a === 127) return true;                    // петля
  if (a === 169 && b === 254) return true;       // link-local и метаданные облаков
  if (a === 172 && b >= 16 && b <= 31) return true; // частная
  if (a === 192 && b === 168) return true;       // частная
  if (a === 100 && b >= 64 && b <= 127) return true; // CGNAT
  if (a === 192 && b === 0) return true;         // служебная
  if (a >= 224) return true;                     // multicast и зарезервированное

  return false;
}

/**
 * Полная проверка: схема, порт и куда имя разрешается.
 *
 * `.local` отбивается до обращения к DNS: mDNS в облаке всё равно не
 * разрешится, а в локальной сети это прямая дорога к соседнему устройству.
 */
export async function проверитьАдрес(значение: string): Promise<Проверка> {
  const разбор = разобратьАдрес(значение);
  if (!разбор.ok) return разбор;

  const имя = разбор.url.hostname.replace(/^\[|\]$/g, "");

  if (имя.endsWith(".local") || имя.endsWith(".internal") || имя === "localhost") {
    return { ok: false, причина: ПРИЧИНА.внутренний };
  }

  // Голый IP разрешать не нужно
  if (/^[\d.]+$/.test(имя) || имя.includes(":")) {
    if (внутреннийАдрес(имя)) {
      return { ok: false, причина: ПРИЧИНА.внутренний };
    }
    return { ok: true, url: разбор.url, адреса: [имя] };
  }

  let записи: { address: string }[];
  try {
    записи = await lookup(имя, { all: true });
  } catch {
    return { ok: false, причина: ПРИЧИНА.имя };
  }
  if (записи.length === 0) {
    return { ok: false, причина: ПРИЧИНА.имя };
  }

  // Достаточно одной внутренней записи, чтобы отказать: round-robin мог бы
  // подсунуть её на втором запросе
  if (записи.some((з) => внутреннийАдрес(з.address))) {
    return { ok: false, причина: ПРИЧИНА.внутренний };
  }

  return { ok: true, url: разбор.url, адреса: записи.map((з) => з.address) };
}
