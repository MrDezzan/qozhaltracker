/**
 * Хозяйство для показа платформы.
 *
 * ПОЧЕМУ ЭТО НЕ КАРТИНКИ И НЕ ЗАГЛУШКИ В РАЗМЕТКЕ
 *
 * Здесь заданы только исходные данные: камеры, зоны, поголовье. Все
 * числа на экранах считаются из них теми же функциями, что и на живой
 * ферме: `assessFarmCondition`, `summariseZoneVisits`, `activityByHour`,
 * `bucketHeadcountByMinute`.
 *
 * Так сделано не из аккуратности. Нарисованный экран расходится с
 * работающим на второй правке: поменяли порог тревоги — на живой ферме
 * стало по-новому, на показе по-старому. И заметит это не разработчик, а
 * человек, которому показывают. Считая по настоящему коду, мы получаем
 * ещё и проверку: если аналитика сломается, экран показа сломается
 * вместе с ней.
 *
 * Время везде отсчитывается от «сейчас», поэтому данные не стареют.
 */

