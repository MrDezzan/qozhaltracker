import { readdirSync } from "node:fs";
import { join } from "node:path";
import { DEMO_CAMERAS } from "./farm";

/**
 * Какие кадры реально лежат в папке показа.
 *
 * ЗАЧЕМ ЧИТАТЬ ПАПКУ, А НЕ ВЕРИТЬ СПИСКУ
 *
 * Сначала имена файлов были записаны в `farm.ts` с расширением `.jpg` и
 * на этом всё держалось. Две беды сразу.
 *
 * Первая: кадры пришли в png. Список требовал jpg, и платформа просила у
 * браузера четыре несуществующих адреса. В окне появлялся значок битой
 * картинки — ровно то, от чего мы уходили, когда убирали пустые окна.
 *
 * Вторая, и она хуже: опечатка в имени или забытый файл вели себя так
 * же. Камера числилась рабочей, окно рисовалось, картинки в нём не было,
 * и выглядело это как неисправность платформы, а не как отсутствие
 * файла.
 *
 * Поэтому источник правды — папка. Что лежит, то и показываем; чего нет,
 * то честно идёт в строку «без сигнала». Расширение любое: png, jpg,
 * webp. Порядок и номера камер по-прежнему из `farm.ts`, папка решает
 * только вопрос «есть кадр или нет».
 */

/** Папка с кадрами. Относительно корня проекта: так её видит и сборка. */
const ПАПКА = join(process.cwd(), "public", "demo");

const РАСШИРЕНИЯ = [".png", ".jpg", ".jpeg", ".webp", ".avif"];

/**
 * Подбор кадров по списку имён файлов.
 *
 * Отделено от чтения диска нарочно: чтением проверку не напишешь, не
 * раскладывая настоящие файлы в настоящую папку, а такая проверка
 * ломается в день, когда в папку положат кадры. Здесь чистая функция, ей
 * на вход список имён.
 */
/** Как может называться файл этого кадра. Регистр не важен. */
function кандидаты(основа: string): string[] {
  return РАСШИРЕНИЯ.map((р) => `${основа}${р}`.toLowerCase());
}

export function подобратьКадры(файлы: string[]): Record<string, string> {
  const найдено: Record<string, string> = {};

  for (const камера of DEMO_CAMERAS) {
    // Камеру, которая по замыслу без сигнала, в папке не ищем: решение
    // «эта на связи, а эта нет» принимается в данных, а не тем, какие
    // файлы кто-то положил рядом.
    //
    const основа = камера.frame;
    if (основа === null) continue;

    // Имена-кандидаты собирает отдельная функция, принимающая строго
    // строку. Это не украшение: пока проверка на null стояла рядом с
    // подстановкой `${камера.frame}`, её можно было убрать и ничего не
    // сломать — null превратился бы в слово «null», файл «null.png» не
    // нашёлся бы, и результат совпал бы по случайности. Теперь снятая
    // проверка не проходит компиляцию.
    const подходящий = файлы.find((имя) =>
      кандидаты(основа).includes(имя.toLowerCase()),
    );
    if (подходящий) найдено[камера.id] = подходящий;
  }

  return найдено;
}

/**
 * Имя файла для каждой камеры, у которой кадр нашёлся.
 *
 * Ключ — идентификатор камеры, значение — имя файла в папке показа.
 * Камеры, для которых файла нет, в карту не попадают.
 */
export function найденныеКадры(): Record<string, string> {
  try {
    return подобратьКадры(readdirSync(ПАПКА));
  } catch {
    // Папки может не быть вовсе: раздел показа должен открываться и
    // тогда, сообщая, что сигнала нет
    return {};
  }
}
