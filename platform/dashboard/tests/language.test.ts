import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * ЯЗЫК ИНТЕРФЕЙСА
 *
 * Правила здесь не про красоту. Экран читает человек, который держит
 * телефон одной рукой, стоит на солнце и первый раз видит нашу
 * систему. У него нет ни времени, ни желания разбирать абзац под
 * кнопкой; он ищет, куда нажать.
 *
 * Отсюда три правила, и каждое держится тестом, а не договорённостью.
 * Договорённость держится, пока о ней помнят: одна кнопка «Создать и
 * выдать доступы», дописанная в спешке, ничего не ломает и никем не
 * замечается, а через полгода таких тридцать.
 *
 * 1. НА КНОПКЕ — ДЕЙСТВИЕ, А НЕ ОБЪЯСНЕНИЕ. Два-три слова. Длинная
 *    подпись всё равно не читается целиком: человек выхватывает первое
 *    слово и жмёт.
 *
 * 2. ПОДПИСЬ ПОД ЗАГОЛОВКОМ — ОДНА СТРОКА. Она отвечает на вопрос «и
 *    что?», а не пересказывает устройство системы.
 *
 * 3. НИКАКИХ ДЛИННЫХ ТИРЕ. Тире в середине фразы почти всегда значит,
 *    что во фразу втиснуто два предложения. Разделив их, мы получаем
 *    текст, который читается с первого раза. Отдельно стоящее «—» в
 *    ячейке таблицы это не тире, а знак «нет данных», и он разрешён.
 *
 * Плюс словарь: слова, которые есть в нашей документации и которых нет
 * в разговоре на ферме. «Учётная запись» вместо «вход», «осуществляется»
 * вместо «идёт». В админских разделах часть таких слов законна: там
 * сидим мы сами, и «миграция» там называется миграцией.
 */

const КОРНИ = ["app", "components", "lib"];

/** Разделы, где сидим мы, а не фермер. */
const НАШИ_РАЗДЕЛЫ = ["app/admin", "app/api", "components/Admin", "components/Training"];

/**
 * Слова, которых фермер от нас не ждёт, и чем их заменить.
 * Запрет мягкий: он смотрит на строки, которые видны на экране.
 */
/*
  Окончание пишется как [а-яё]*, а не \w*, и это не придирка. В JS
  \w это [A-Za-z0-9_]: кириллицу он не ловит. Первая версия словаря
  была написана через \w, выглядела рабочей и не находила «учётной
  записи» — проверка мутацией это и показала.
*/
const ОКОНЧАНИЕ = "[а-яё]*";
const слово = (корни: string) => new RegExp(корни.replace(/~/g, ОКОНЧАНИЕ), "i");

/*
  ЧТО ИМЕННО ЗАПРЕЩЕНО, И ПОЧЕМУ СПИСОК ИЗМЕНИЛСЯ

  Сначала здесь запрещались деловые слова: «учётная запись», «данные
  пользователя», «необходимо». Расчёт был на речь фермера в загоне.
  Ошибка в том, что этим экраном пользуется не только фермер: его
  показывают на переговорах, по нему принимают работу, рядом с ним
  лежит договор. Разговорный тон там читается не как забота, а как
  несделанная работа.

  Поэтому запрещено ровно две вещи.

  РАЗГОВОРНОЕ. «Позвоните нам», «мы посмотрим», «зато быстрее», «пока
  пусто» — обороты из переписки, а не из продукта. Вместо них
  безличное: «обратитесь в техническую поддержку», «данных нет».

  КАНЦЕЛЯРИТ И ЖАРГОН. «Осуществляется» вместо «идёт», «производится»
  вместо «выполняется», «дашборд» вместо «экран фермы». Деловой язык и
  канцелярит это разные вещи: первый называет, второй прячет.

  «Учётная запись», «оборудование», «зона кормления» разрешены и
  используются: это термины продукта, одни и те же в интерфейсе, в
  договоре и в разговоре с монтажником.
*/
const СЛОВАРЬ: Array<{ плохо: RegExp; вместо: string; всюду?: boolean }> = [
  { плохо: слово("позвоните нам"), вместо: "обратитесь в техническую поддержку", всюду: true },
  { плохо: слово("напишите нам"), вместо: "обратитесь в техническую поддержку", всюду: true },
  { плохо: слово("мы посмотрим"), вместо: "проверит техническая служба", всюду: true },
  { плохо: слово("пока пусто"), вместо: "данных нет", всюду: true },
  { плохо: слово("зато\\b"), вместо: "без противопоставления", всюду: true },
  { плохо: слово("осуществля~"), вместо: "идёт, выполняется", всюду: true },
  { плохо: слово("производится"), вместо: "выполняется", всюду: true },
  { плохо: слово("дашборд~"), вместо: "экран фермы", всюду: true },
];

function файлы(корень: string): string[] {
  const найдено: string[] = [];
  const обойти = (папка: string) => {
    for (const имя of readdirSync(папка)) {
      const путь = join(папка, имя);
      if (statSync(путь).isDirectory()) обойти(путь);
      else if (путь.endsWith(".tsx") || путь.endsWith(".ts")) найдено.push(путь);
    }
  };
  обойти(join(process.cwd(), корень));
  return найдено;
}

const ВСЁ = КОРНИ.flatMap(файлы);

function короткий(путь: string): string {
  return relative(process.cwd(), путь);
}

function фермерский(путь: string): boolean {
  const п = короткий(путь);
  return !НАШИ_РАЗДЕЛЫ.some((наш) => п.startsWith(наш));
}

/** Код без комментариев: комментарии пишутся для нас и правил не знают. */
function безКомментариев(текст: string): string {
  return текст
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

/**
 * Похоже ли найденное на код, а не на фразу с экрана.
 *
 * Выражение ниже цепляет и куски кода: шаблонная строка с русским
 * комментарием внутри, длинный тернарник, целая разметка между двумя
 * тегами. На запрете тире это почти не мешало, а запрет восклицательных
 * знаков сразу споткнулся о `if (!response.ok)`: тест покраснел на трёх
 * файлах, где никто ни на кого не кричит.
 *
 * Признак простой: во фразе с экрана не бывает фигурных скобок,
 * присваивания, точки с запятой и имён классов.
 */
function похожеНаКод(строка: string): boolean {
  return /[{}();=]|className|=>|\bconst\b|\bfunction\b|\breturn\b/.test(
    строка,
  );
}

/** Строки, которые доходят до экрана. */
export function видимыеСтроки(код: string): string[] {
  const найдено: string[] = [];
  const текст = безКомментариев(код);
  const шаблон =
    /"([^"\n]*[А-Яа-яЁё][^"\n]*)"|>\s*([^<>{}\n]*[А-Яа-яЁё][^<>{}\n]*?)\s*<|`([^`]*[А-Яа-яЁё][^`]*)`/g;
  for (const м of текст.matchAll(шаблон)) {
    const строка = (м[1] ?? м[2] ?? м[3]).replace(/\s+/g, " ").trim();
    if (строка.length >= 3 && !похожеНаКод(строка)) найдено.push(строка);
  }
  return найдено;
}

/** Подписи кнопок и ссылок-кнопок. */
export function подписиКнопок(код: string): string[] {
  const найдено: string[] = [];
  const текст = безКомментариев(код);
  for (const м of текст.matchAll(
    /<(Button|button)\b[^>]*>([\s\S]{0,400}?)<\/\1>/g,
  )) {
    const тело = м[2].replace(/\s+/g, " ").trim();
    // Внутри может стоять тернарник: «{pending ? "Создаём…" : "Создать"}».
    // Тогда подписи это его ветки, а не всё выражение целиком
    const ветки = [...тело.matchAll(/"([^"\n]*[А-Яа-яЁё][^"\n]*)"/g)].map(
      (в) => в[1],
    );
    if (ветки.length) найдено.push(...ветки);
    else if (/^[^<>{}]*[А-Яа-яЁё][^<>{}]*$/.test(тело)) найдено.push(тело);
  }
  return найдено;
}

const МАКС_СЛОВ_НА_КНОПКЕ = 3;
const МАКС_ЗНАКОВ_НА_КНОПКЕ = 24;
const МАКС_ЗНАКОВ_В_ПОДПИСИ = 62;

describe("На кнопке действие, а не объяснение", () => {
  it("файлов для проверки нашлось достаточно", () => {
    // Проверка, ничего не нашедшая, выглядит как пройденная
    expect(ВСЁ.length).toBeGreaterThan(40);
  });

  it("подписи кнопок короткие", () => {
    const длинные: string[] = [];
    for (const путь of ВСЁ) {
      for (const подпись of подписиКнопок(readFileSync(путь, "utf8"))) {
        const слов = подпись.split(/\s+/).filter(Boolean).length;
        if (слов > МАКС_СЛОВ_НА_КНОПКЕ || подпись.length > МАКС_ЗНАКОВ_НА_КНОПКЕ) {
          длинные.push(`${короткий(путь)}: «${подпись}»`);
        }
      }
    }
    expect(
      длинные,
      `кнопка это действие в ${МАКС_СЛОВ_НА_КНОПКЕ} слова, а не объяснение`,
    ).toEqual([]);
  });
});

describe("Подпись под заголовком в одну строку", () => {
  it("description и hint не превращаются в абзац", () => {
    const длинные: string[] = [];
    const шаблон = /\b(description|hint)=(?:"([^"]*)"|\{"([^"]*)"\})/g;
    for (const путь of ВСЁ) {
      const код = безКомментариев(readFileSync(путь, "utf8"));
      for (const м of код.matchAll(шаблон)) {
        const текст = (м[2] ?? м[3] ?? "").replace(/\s+/g, " ").trim();
        if (!/[А-Яа-яЁё]/.test(текст)) continue;
        if (текст.length > МАКС_ЗНАКОВ_В_ПОДПИСИ) {
          длинные.push(`${короткий(путь)} (${текст.length}): «${текст}»`);
        }
      }
    }
    expect(
      длинные,
      `подпись под заголовком до ${МАКС_ЗНАКОВ_В_ПОДПИСИ} знаков: длиннее её не дочитывают`,
    ).toEqual([]);
  });
});

describe("Без длинных тире", () => {
  it("в видимом тексте нет тире посреди фразы", () => {
    const сТире: string[] = [];
    for (const путь of ВСЁ) {
      for (const строка of видимыеСтроки(readFileSync(путь, "utf8"))) {
        // Одиноко стоящее «—» это «нет данных» в ячейке таблицы
        if (строка === "—") continue;
        if (строка.includes("—")) сТире.push(`${короткий(путь)}: «${строка}»`);
      }
    }
    expect(
      сТире,
      "тире посреди фразы почти всегда значит два предложения в одном",
    ).toEqual([]);
  });
});

describe("Деловой язык, а не переписка", () => {
  it("нет разговорных оборотов и канцелярита", () => {
    const нарушители: string[] = [];
    for (const путь of ВСЁ) {
      const наш = !фермерский(путь);
      for (const строка of видимыеСтроки(readFileSync(путь, "utf8"))) {
        for (const { плохо, вместо, всюду } of СЛОВАРЬ) {
          if (наш && !всюду) continue;
          const м = строка.match(плохо);
          if (м) {
            нарушители.push(
              `${короткий(путь)}: «${м[0]}» в «${строка}» — лучше «${вместо}»`,
            );
          }
        }
      }
    }
    expect(нарушители).toEqual([]);
  });
});

describe("Без восклицаний", () => {
  it("в видимом тексте нет восклицательных знаков", () => {
    // Восклицательный знак в интерфейсе либо кричит на человека, либо
    // радуется вместо него. Ни то, ни другое продукту не нужно
    const сКриком: string[] = [];
    for (const путь of ВСЁ) {
      for (const строка of видимыеСтроки(readFileSync(путь, "utf8"))) {
        if (строка.includes("!")) сКриком.push(`${короткий(путь)}: «${строка}»`);
      }
    }
    expect(сКриком).toEqual([]);
  });
});

describe("Сами проверки работают", () => {
  it("длинную кнопку видно", () => {
    const код = '<Button type="submit">Создать и выдать доступы клиенту</Button>';
    expect(подписиКнопок(код)).toEqual(["Создать и выдать доступы клиенту"]);
  });

  it("ветки тернарника на кнопке разбираются по отдельности", () => {
    const код = '<Button>{pending ? "Создаём…" : "Создать ферму"}</Button>';
    expect(подписиКнопок(код)).toEqual(["Создаём…", "Создать ферму"]);
  });

  it("комментарий с тире проверку не роняет", () => {
    // Иначе пришлось бы писать пояснения телеграфным стилем
    expect(видимыеСтроки("// это — комментарий\nconst x = 1;")).toEqual([]);
  });

  it("видимую строку с тире находит", () => {
    expect(видимыеСтроки('let s = "было — стало";')).toEqual(["было — стало"]);
  });

  it("кусок кода за фразу не принимается", () => {
    // Иначе запрет восклицательных знаков спотыкался о if (!response.ok)
    const код = 'if (!response.ok) { setError("Кадр не получен"); }';
    expect(видимыеСтроки(код)).toEqual(["Кадр не получен"]);
  });

  it("словарь ловит русские окончания", () => {
    // Через \w эта проверка молча не находила ничего: в JS \w это
    // латиница. Заметили только мутацией
    const осуществление = СЛОВАРЬ.find((с) =>
      "осуществляется".match(с.плохо),
    );
    expect(осуществление).toBeDefined();
    expect("Съёмка осуществляется круглосуточно").toMatch(осуществление!.плохо);
  });
});
