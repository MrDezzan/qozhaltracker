import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

// Путь от корня проекта: vitest здесь запускается в браузерном
// окружении, где import.meta.url не файловый
const css = readFileSync(join(process.cwd(), "app/globals.css"), "utf8");

/*
  Разбор значений идёт по коду без комментариев. В globals.css поломка с
  самоссылкой разобрана словами, и строка `--color-surface:
  var(--color-surface)` внутри объяснения попадалась регулярному
  выражению раньше настоящего объявления: контраст считался от мусора и
  выходил NaN, а NaN не больше 4.5, так что тест краснел без причины.
*/
const кодCSS = css
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/^\s*\/\/.*$/gm, "");

/** Относительная яркость по WCAG. */
function яркость(hex: string): number {
  const ч = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const л = ч.map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * л[0] + 0.7152 * л[1] + 0.0722 * л[2];
}

function контраст(a: string, b: string): number {
  const [светлее, темнее] = [яркость(a), яркость(b)].sort((x, y) => y - x);
  return (светлее + 0.05) / (темнее + 0.05);
}

/**
 * Значение токена, разобранное из самого CSS.
 *
 * Раньше пары для проверки контраста стояли здесь шестнадцатеричными
 * кодами: ["ответ «всё спокойно»", "#15803d", "#dcfce7"]. В день, когда
 * палитру сменили на синюю с молочной, тест остался зелёным: он честно
 * считал контраст двух цветов, которых в продукте больше нет. Проверка
 * жила своей жизнью.
 *
 * Поэтому теперь тест читает CSS: имена ролей остаются в списке, а
 * значения берутся из файла и разворачиваются по цепочке var().
 */
function значение(имя: string, глубина = 0): string {
  if (глубина > 6) throw new Error(`циклическая ссылка в --${имя}`);
  const найдено = кодCSS.match(new RegExp(`--${имя}:\\s*([^;]+);`));
  if (!найдено) throw new Error(`в globals.css нет токена --${имя}`);
  const сырое = найдено[1].trim();
  const ссылка = сырое.match(/^var\(--([a-z0-9-]+)\)$/i);
  if (ссылка) return значение(ссылка[1], глубина + 1);
  return сырое;
}

/**
 * Контраст проверяется числом, а не глазами.
 *
 * Глазами он проверяется на хорошем мониторе в помещении — там сходится
 * почти всё. Экран смотрят на солнце, и там разница между 3:1 и 4.5:1
 * это разница между «прочитал» и «не увидел».
 */
describe("Цвета читаются", () => {
  const ОБЫЧНЫЙ = 4.5;
  const КРУПНЫЙ = 3;
  // WCAG 1.4.11: контур поля и кнопки это тоже информация
  const КОНТУР = 3;

  it.each([
    ["текст на панели", "color-ink", "color-surface", ОБЫЧНЫЙ],
    ["приглушённый текст", "color-muted", "color-surface", ОБЫЧНЫЙ],
    ["подписи под числами", "color-faint", "color-surface", ОБЫЧНЫЙ],
    ["текст на фоне страницы", "color-ink", "color-bg", ОБЫЧНЫЙ],
    ["приглушённый на фоне страницы", "color-muted", "color-bg", ОБЫЧНЫЙ],
    ["текст на основной кнопке", "color-on-brand", "color-brand", ОБЫЧНЫЙ],
    ["текст на кнопке при наведении", "color-on-brand", "color-accent", ОБЫЧНЫЙ],
    ["текст на тёмной плоскости", "color-on-dark", "color-dark", ОБЫЧНЫЙ],
    ["второй текст на тёмной плоскости", "color-on-dark-muted", "color-dark", ОБЫЧНЫЙ],
    ["мелкий текст на тёмной плоскости", "color-on-dark-faint", "color-dark", КРУПНЫЙ],
    ["голубой на тёмной плоскости", "color-on-dark-accent", "color-dark", ОБЫЧНЫЙ],
    ["ответ «отклонений нет»", "color-calm", "color-calm-bg", КРУПНЫЙ],
    ["ответ «требует внимания»", "color-watch", "color-watch-bg", КРУПНЫЙ],
    ["ответ «требуется вмешательство»", "color-trouble", "color-trouble-bg", КРУПНЫЙ],
    ["состояние на панели", "color-calm", "color-surface", ОБЫЧНЫЙ],
    ["внимание на панели", "color-watch", "color-surface", ОБЫЧНЫЙ],
    ["вмешательство на панели", "color-trouble", "color-surface", ОБЫЧНЫЙ],
    // Кнопка действия: заливка тёплая, буквы тёмные. В макете сайта на
    // ней белые буквы, и это 2.77 — то есть подпись не читается
    ["текст на кнопке действия", "color-on-action", "color-action", ОБЫЧНЫЙ],
    // Сама заливка терракоты к молочному даёт всего 2.52: край кнопки
    // на светлом фоне терялся бы. Поэтому у кнопки есть контур, и
    // проверяется он, а не заливка
    ["контур кнопки действия к фону", "color-action-hover", "color-bg", КОНТУР],
    ["контур кнопки действия к панели", "color-action-hover", "color-surface", КОНТУР],
    ["белый на тёмной терракоте", "color-surface", "color-action-hover", ОБЫЧНЫЙ],
    ["заголовок раздела шалфеем", "color-leaf", "color-bg", ОБЫЧНЫЙ],
    ["заголовок раздела на панели", "color-leaf", "color-surface", ОБЫЧНЫЙ],
    ["контур поля к панели", "color-line-strong", "color-surface", КОНТУР],
    ["контур поля к фону страницы", "color-line-strong", "color-bg", КОНТУР],
  ])("%s", (_имя, текст, фон, нужно) => {
    expect(контраст(значение(текст as string), значение(фон as string))).toBeGreaterThanOrEqual(
      нужно as number,
    );
  });

  it("каждая роль из списка есть в CSS", () => {
    // Иначе переименование токена превратило бы проверку в пустышку:
    // ровно это и случилось при смене палитры
    expect(() => значение("color-ink")).not.toThrow();
    expect(() => значение("color-nesushchestvuyushchiy")).toThrow();
  });
});

describe("Размеры под руку в перчатке", () => {
  it("касание не меньше 48 пикселей", () => {
    // Ниже этого палец промахивается по соседней кнопке, а промах на
    // экране «тревоги» стоит дороже сэкономленного места
    expect(css).toContain("--tap-min: 3rem");
  });

  it("основной текст крупнее обычных 16", () => {
    // Экран телефона на солнце, рука на весу, человек стоит
    const найдено = css.match(/--text-base:\s*([\d.]+)rem/);
    expect(найдено).not.toBeNull();
    expect(Number(найдено![1])).toBeGreaterThan(1);
  });

  it("самый мелкий текст не мельче 13 пикселей", () => {
    const найдено = css.match(/--text-xs:\s*([\d.]+)rem/);
    expect(Number(найдено![1]) * 16).toBeGreaterThanOrEqual(13);
  });
});

describe("Правила, которые легко потерять", () => {
  it("след фокуса не убран", () => {
    // Без него с клавиатуры непонятно, где ты находишься
    expect(css).toContain(":focus-visible");
    expect(css).toMatch(/outline:\s*2px solid/);
  });

  it("движение выключается системной настройкой", () => {
    expect(css).toContain("prefers-reduced-motion");
  });

  it("низ страницы не прячется под полосой разделов", () => {
    expect(css).toContain("env(safe-area-inset-bottom)");
  });

  it("три слоя токенов на месте", () => {
    // Примитив — сырое значение, смысл — зачем он, компонент — где.
    // Смешав их, мы вернёмся к правке цвета в тридцати файлах
    expect(css).toContain("--navy:");
    expect(css).toContain("--color-brand: var(--navy)");
    expect(css).toContain("--button-height: var(--tap-min)");
  });
});
