import { ReactNode } from "react";

/**
 * Обёртка страницы.
 *
 * Появилась потому, что одна и та же строка отступов была скопирована
 * в девять файлов, и в трёх из них уже разошлась: где-то `py-6`, где-то
 * `py-10`, у одной страницы другая ширина. По отдельности незаметно, а
 * при переходе между разделами содержимое дёргается — и человек видит
 * не «разные страницы», а «что-то подгрузилось криво».
 *
 * `pb-nav` здесь обязателен: на телефоне внизу полоса разделов, и без
 * отступа последняя карточка прячется под ней. Забыть его на одной
 * странице из девяти — ровно тот случай, который заметит не
 * разработчик, а человек, не нашедший кнопку «Сохранить».
 */
export function Page({
  children,
  width = "wide",
}: {
  children: ReactNode;
  /** `narrow` — для форм и чтения: строка длиной в экран не читается */
  width?: "wide" | "narrow";
}) {
  const ширина = width === "narrow" ? "max-w-3xl" : "max-w-6xl";
  return (
    <div className={`pb-nav mx-auto ${ширина} px-4 py-5 sm:px-6 sm:py-8`}>
      {children}
    </div>
  );
}
