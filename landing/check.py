#!/usr/bin/env python3
"""
Проверка лендинга. Запуск: python3 landing/check.py

Ловит то, что глазами не видно и вылезает уже у клиента:

  1. Ключ есть в разметке, а перевода на каком-то языке нет. На сайте
     это выглядит как английский кусок посреди казахского текста —
     причём только на том языке, который вы сами не проверяли.

  2. Статический текст в разметке разошёлся со словарём. Он виден те
     доли секунды, пока не отработал скрипт, и попадает в поисковую
     выдачу. Один раз тут уже было «Пять вещей» над шестью карточками.

  3. Насыщенность шрифта, которой нет среди подключённых: браузер
     округлит её молча.

  4. Стили и переменные, оставшиеся от удалённых блоков.

  5. Телефон, почта или логотип остались заглушками.

Каждая проверка проверена мутацией: сломай то, что она стережёт, и она
обязана заругаться. Проверка, которую нельзя заставить упасть, ничего
не проверяет.
"""

import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAGE = os.path.join(HERE, "index.html")
PLACEHOLDER = "77000000000"


def pairs(block):
    """Все «ключ: "значение"» в куске словаря, включая несколько в строке."""
    return dict(re.findall(r'(\w+):\s*"((?:[^"\\]|\\.)*)"', block))



def найти_словарь(page, lang):
    """Тело словаря переводов по имени языка.

    Раньше здесь стояло выражение, прибитое к отступу: `\n  ru: {` и
    закрывающая скобка ровно через два пробела. Файл прогнали через
    форматировщик, отступ стал шестью пробелами — и проверка объявила все
    три словаря пропавшими. Файл при этом был цел, а тесты зелёные.

    Проверка не должна зависеть от того, чем отформатирован файл. Поэтому
    скобки считаются, а не угадываются по отступу.
    """
    начало = re.search(r"\n\s*%s:\s*\{" % lang, page)
    if not начало:
        return None

    глубина = 0
    for i in range(начало.end() - 1, len(page)):
        if page[i] == "{":
            глубина += 1
        elif page[i] == "}":
            глубина -= 1
            if глубина == 0:
                return page[начало.end():i]
    return None


# ---------------------------------------------------------------------------
# Признаки «сделано за вечер»
# ---------------------------------------------------------------------------
# Список ниже — не вкусовщина. Это набор приёмов из стандартной заготовки
# генератора страниц: градиент через фиолетовый, мягкие тени, три
# одинаковые карточки, подпрыгивание при наведении. Каждый по отдельности
# безобиден, но вместе они дают ровно тот вид, по которому посетитель
# узнаёт страницу, сделанную не для него, а по образцу.
#
# Проверка нужна именно автоматическая: приёмы возвращаются по одному,
# при мелкой правке через месяц, и глазами такое не ловится.

def check_ai_tells(page, styles):
    found = []

    # Градиент как ОФОРМЛЕНИЕ. Оформление держится на бумаге, краске и
    # линейках: фиолетовый перелив поперёк карточки узнаётся мгновенно.
    #
    # Но у градиента есть и рабочее применение: растушевать фотографию к
    # краю и притушить её под белым текстом. Без этого заголовок в три
    # строки ложится на светлое небо и не читается — то есть запрет
    # ухудшал бы страницу, а не улучшал.
    #
    # Поэтому запрещён градиент вообще, кроме двух мест: маски и вуали
    # над фотографией первого экрана. Они помечены в стилях.
    РАЗРЕШЁННЫЕ_ГРАДИЕНТЫ = ("mask-image", ".hero::after")
    for кусок in re.findall(r"[^;{}]*(?:linear|radial|conic)-gradient[^;]*;", styles):
        строка = кусок.strip()
        # Вуаль объявлена внутри .hero::after: ищем её по соседству
        начало = styles.find(строка)
        окрестность = styles[max(0, начало - 400):начало]
        if any(маркер in строка or маркер in окрестность
               for маркер in РАЗРЕШЁННЫЕ_ГРАДИЕНТЫ):
            continue
        found.append(f"градиент в стилях: {строка[:60]}")

    # Тени. Приподнятая карточка — самый узнаваемый признак заготовки
    shadows = [
        one for one in re.findall(r"box-shadow:\s*([^;]+);", styles)
        if "none" not in one
    ]
    if shadows:
        found.append("box-shadow (%d шт.)" % len(shadows))

    # Ровно три карточки в ряд — подпись жанра
    if re.search(r"repeat\(3,\s*(1fr|minmax)", styles):
        found.append("сетка repeat(3, 1fr)")

    # Скругления берутся из токенов, а не подбираются на глаз.
    #
    # Раньше здесь стоял запрет на радиус от 12 пикселей: считалось, что
    # пухлый угол выдаёт заготовку. Правило умерло вместе со сменой
    # макета — новый дизайн-код требует 10, 18 и 28 пикселей, и запрет
    # ругался бы на каждую карточку.
    #
    # Хуже того, к этому моменту правило почти ослепло: все радиусы в
    # стилях уже шли через var(--r-…), а выражение искало только числа.
    # Оно молчало не потому, что всё хорошо, а потому что смотрело не
    # туда.
    #
    # Осталась суть: радиус должен быть один из объявленных. Сам по себе
    # мягкий угол не порок, а вот пять разных мягких углов на одной
    # странице — это и есть «собрано за вечер».
    объявленные = set(re.findall(r"(--r-[a-z]+):", styles))
    самодельные = []
    for кусок in re.findall(r"border-radius:\s*([^;]+);", styles):
        for значение in кусок.split():
            if значение in ("0", "0px", "50%"):
                continue
            # Скругление экрана телефона задано в процентах от корпуса:
            # это доля физического предмета, а не ступень нашей шкалы.
            # Подгонять её под карточки незачем
            if значение == "var(--screen-radius)":
                continue
            if значение.startswith("var(--r-"):
                имя = значение[len("var("):-1]
                if имя not in объявленные:
                    самодельные.append(значение)
                continue
            самодельные.append(значение)
    if самодельные:
        found.append(
            "радиус задан не токеном (%s)" % ", ".join(sorted(set(самодельные))[:4])
        )

    # Подпрыгивание при наведении
    if re.search(r":hover[^{]*\{[^}]*transform", styles):
        found.append("transform при наведении")

    # Эмодзи в тексте. В деловом тексте они читаются как попытка оживить
    # то, что нечем оживить по существу
    if re.search("[\U0001F300-\U0001FAFF\u2600-\u27BF]", page):
        found.append("эмодзи в тексте")

    # Слова-пустышки: ни одно не сообщает читателю ничего о продукте
    empty_words = [
        "инновацион", "революцион", "уникальн", "передов",
        "не просто ", "в мире, где", "seamless", "cutting-edge",
        "game-chang", "revolutioniz",
    ]
    text = re.sub(r"<[^>]+>", " ", page).lower()
    hits = [one for one in empty_words if one in text]
    if hits:
        found.append("слова-пустышки: %s" % ", ".join(hits))

    if not found:
        return []
    return ["признаки шаблонной вёрстки — %s" % "; ".join(found)]



