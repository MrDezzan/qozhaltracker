def check_boot(page):
    problems = []

    # Предохранитель. Без него одна поломка скрипта прячет ВЕСЬ сайт за
    # синим экраном навсегда: снимать заставку станет некому
    head = page.split("</head>", 1)[0]
    if "booting" in head and 'classList.remove("booting"' not in head:
        problems.append(
            "заставка включается в <head>, но предохранитель там не стоит — "
            "поломка основного скрипта оставит синий экран навсегда"
        )

    # Заставка обязана прятаться по умолчанию. Правило вида
    # `.boot { display: flex }` показало бы синий экран тем, у кого не
    # выполнился скрипт, — то есть навсегда
    # Только содержимое <style>, без <head> вокруг него. Иначе в «стили»
    # попадают комментарии в шапке, где имена классов упоминаются
    # словами, — и проверка срабатывает на пересказ вместо кода
    styles = page.split("<style>", 1)[1].split("</style>", 1)[0]
    if ".boot {" in styles and "display: none" not in styles.split(".boot {", 1)[1][:80]:
        problems.append(
            ".boot виден по умолчанию — без JS страница останется под заставкой"
        )

    return problems


def предки_по_классам(page):
    """class -> множество классов всех его предков (и его самого).

    Нужно, чтобы отличить законный случай от поломки: .phone-screen
    лежит ВНУТРИ .phone, и переменная до него наследуется. А .how-grid —
    родитель .phone, и туда она не дойдёт.
    """
    пустые = {"meta", "link", "br", "hr", "img", "input", "source", "path"}
    предки = {}
    стек = []
    for m in re.finditer(r"<(/?)([a-z0-9]+)([^>]*?)(/?)>", page, re.I):
        закр, тег, атрибуты, сам = m.groups()
        тег = тег.lower()
        if закр:
            while стек and стек.pop()[0] != тег:
                pass
            continue
        классы = set()
        к = re.search(r'class="([^"]*)"', атрибуты)
        if к:
            классы = set(к.group(1).split())
        сверху = set()
        for _, кл in стек:
            сверху |= кл
        for кл in классы:
            предки.setdefault(кл, set()).update(сверху | классы)
        if тег not in пустые and not сам:
            стек.append((тег, классы))
    return предки


def check_vars_scope(page):
    """Переменная, объявленная в потомке и использованная у предка.

    CSS-переменные наследуются вниз, не вверх. Если --phone-w объявлен в
    .phone, а использован в grid-template-columns у .how-grid, значение
    там НЕ существует: вся строка становится недействительной, и сетка
    молча схлопывается в одну колонку. Браузер об этом не сообщает
    никак — ни ошибки, ни предупреждения. Именно так телефон на главной
    однажды уехал из правой колонки в центр.

    Лечится объявлением в :root.
    """
    problems = []
    styles = page.split("<style>", 1)[1].split("</style>", 1)[0]
    # комментарии выкинуть: в них имена переменных упоминаются словами
    styles = re.sub(r"/\*.*?\*/", "", styles, flags=re.S)
    предки = предки_по_классам(page)

    объявлена, использована = {}, {}
    for селектор, тело in re.findall(r"([^{}]+)\{([^{}]*)\}", styles):
        сел = селектор.strip().split("\n")[-1].strip()
        for имя in re.findall(r"(--[a-z0-9-]+)\s*:", тело):
            объявлена.setdefault(имя, set()).add(сел)
        for имя in re.findall(r"var\((--[a-z0-9-]+)", тело):
            использована.setdefault(имя, set()).add(сел)

    def класс(селектор):
        м = re.fullmatch(r"\.([a-z0-9-]+)", селектор.strip())
        return м.group(1) if м else None

    for имя, где_исп in sorted(использована.items()):
        где_объ = объявлена.get(имя)
        if not где_объ:
            problems.append("%s используется, но нигде не объявлена" % имя)
            continue
        if ":root" in где_объ:
            continue
        объ_классы = {класс(с) for с in где_объ} - {None}
        if not объ_классы:
            continue
        for сел in sorted(где_исп):
            к = класс(сел)
            if k_ok(к, объ_классы, предки):
                continue
            problems.append(
                "%s объявлена в %s, а использована в %s — вверх переменные "
                "не наследуются, правило молча отвалится. Объявите в :root"
                % (имя, ", ".join(sorted(где_объ)), сел)
            )
    return problems


def k_ok(используется_в, объявлена_в, предки):
    """Достаёт ли переменная до элемента: он сам или его потомок."""
    if используется_в is None:
        return True          # не простой селектор — не судим
    if используется_в in объявлена_в:
        return True
    return bool(предки.get(используется_в, set()) & объявлена_в)


def main():
    page = io.open(PAGE, encoding="utf-8").read()
    problems = []

    used = set(re.findall(r'data-i18n="([^"]+)"', page))

    problems += check_vars_scope(page)

    # Часть ключей ставится не разметкой, а скриптом: замечание в
    # калькуляторе меняется от ответов, единица измерения и текст письма
    # в WhatsApp собираются на лету. Без этого проверка объявляла бы
    # живой перевод мёртвым и требовала его удалить
    script = page.split("<script>")[-1]
    used |= set(re.findall(r'dict\.(\w+)', script))
    used |= set(re.findall(r'return "(\w+)";', script))
    # Тексты ошибок скрипт достаёт по имени: { key: "eHead" } → dict[g.key]
    used |= set(re.findall(r'key: "(\w+)"', script))

    dicts = {}
    for lang in ("ru", "kk", "en"):
        тело = найти_словарь(page, lang)
        if тело is None:
            problems.append("словарь %s не найден" % lang)
            continue
        dicts[lang] = pairs(тело)

    for lang, words in dicts.items():
        missing = sorted(used - set(words))
        if missing:
            problems.append("%s: нет перевода — %s" % (lang, ", ".join(missing)))

        unused = sorted(k for k in words if not k.startswith("_") and k not in used)
        if unused:
            problems.append(
                "%s: ключи есть в словаре, но нигде не показываются — %s"
                % (lang, ", ".join(unused))
            )

    ru = dicts.get("ru", {})
    for key, static in re.findall(r'data-i18n="([^"]+)"[^>]*>([^<]+)<', page):
        want = ru.get(key)
        if want is None or "<br>" in want:
            continue
        if " ".join(static.split()) != " ".join(want.split()):
            problems.append(
                "статический текст разошёлся со словарём, ключ %s:\n"
                "      в разметке: %s\n"
                "      в словаре:  %s" % (key, " ".join(static.split()), want)
            )

    # Шрифты подключены статическими начертаниями. Вес, которого нет в
    # подключённых, браузер молча округлит до ближайшего — и заголовок
    # окажется не той толщины, а понять почему неоткуда
    loaded = set()
    for family in re.findall(r"family=(\w+):wght@([\d;.]+)", page):
        for weight in family[1].split(";"):
            loaded.add(weight.strip())
    if loaded:
        # Имя не `used`: так уже перекрыли набор ключей выше, и итоговая
        # строка стала считать насыщенности вместо переводов
        weights = set(re.findall(r"font-weight:\s*(\d{3})", page))
        stray = sorted(weights - loaded)
        if stray:
            problems.append(
                "насыщенности %s нет среди подключённых (%s) — браузер округлит молча"
                % (", ".join(stray), ", ".join(sorted(loaded)))
            )

    # Классы, для которых остались стили, а разметки уже нет.
    #
    # За одну переделку тут трижды удалялись блоки — «статус», анимация
    # сканирования, макет телефона. Стили после них остаются молча: файл
    # растёт, а следующий человек не понимает, что можно трогать.
    body = page.split("</style>", 1)[-1]
    styled = set(re.findall(r"\.([a-z][a-z0-9-]*)\s*[,{:]", page.split("</style>", 1)[0]))
    in_html = set(re.findall(r'class="([^"]+)"', body))
    used_classes = {one for group in in_html for one in group.split()}
    used_classes |= set(re.findall(r'classList\.\w+\("([^"]+)"', page))
    used_classes |= set(re.findall(r'querySelectorAll?\("\.([a-z][a-z0-9-]*)"', page))

    orphans = sorted(styled - used_classes)
    if orphans:
        problems.append(
            "стили есть, разметки нет — %s" % ", ".join("." + one for one in orphans)
        )

    # Переменные, объявленные и никем не использованные. Та же беда, что
    # с классами: остаются от удалённых блоков и сбивают с толку. Так уже
    # осиротели --ink-3 от убранной кнопки и --red от макета телефона
    # Только содержимое <style>, без <head> вокруг него. Иначе в «стили»
    # попадают комментарии в шапке, где имена классов упоминаются
    # словами, — и проверка срабатывает на пересказ вместо кода
    styles = page.split("<style>", 1)[1].split("</style>", 1)[0]
    declared = set(re.findall(r"^\s*(--[a-z0-9-]+):", styles, re.M))
    referenced = set(re.findall(r"var\((--[a-z0-9-]+)", styles))
    unused_vars = sorted(declared - referenced)
    if unused_vars:
        problems.append(
            "переменные объявлены, но нигде не используются — %s"
            % ", ".join(unused_vars)
        )

    # Каждый локальный файл, на который ссылается страница, должен
    # лежать рядом. Пропавшая иконка — пустой лист во вкладке, пропавшая
    # картинка — дыра в макете, и обе замечаются не сразу
    assets = set(re.findall(r'(?:src|href)="((?!https?:|#|mailto:|tel:)[^"]+\.(?:png|jpg|jpeg|webp|svg|ico|gif))"', page))
    missing = sorted(one for one in assets
                     if not os.path.exists(os.path.join(HERE, one)))
    if missing:
        problems.append("нет файлов, на которые ссылается страница — %s"
                        % ", ".join(missing))

    if PLACEHOLDER in page:
        problems.append(
            "номер телефона остался заглушкой — правьте CONTACT.phone в index.html"
        )

    if "hello@example.com" in page:
        problems.append(
            "почта осталась заглушкой — правьте CONTACT.email в index.html"
        )

    # Свой знак не положили — в шапке рисованный запасной. Страница при
    # этом не ломается, но клиент видит не ваш логотип
    if re.search(r'src="(logo\.\w+)"', page):
        wanted = re.search(r'src="(logo\.\w+)"', page).group(1)
        if not os.path.exists(os.path.join(HERE, wanted)):
            problems.append(
                "нет файла %s — в шапке пока рисованный знак. "
                "Положите КВАДРАТНЫЙ знак «Q» без слова под ним: "
                "вертикальная связка в шапке нечитаема" % wanted
            )

    problems.extend(check_ai_tells(page, styles))
    problems.extend(check_boot(page))

    print("ключей в разметке: %d" % len(used))
    for lang, words in dicts.items():
        print("  %s: %d" % (lang, len(words)))
    print()

    if problems:
        print("ПРОБЛЕМЫ (%d):" % len(problems))
        for one in problems:
            print("  - %s" % one)
        return 1

    print("всё сходится")
    return 0


if __name__ == "__main__":
    sys.exit(main())
